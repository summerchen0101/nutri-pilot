#!/usr/bin/env node
/**
 * Regenerates ppt/export/* from ppt/palette.json
 * Usage: node scripts/ppt-export-palette.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const palette = JSON.parse(readFileSync(join(root, 'ppt/palette.json'), 'utf8'));
const outDir = join(root, 'ppt/export');
mkdirSync(outDir, { recursive: true });

const flat = [
  ['primary', palette.colors.primary.DEFAULT],
  ['primary-dark', palette.colors.primary.dark],
  ['primary-light', palette.colors.primary.light],
  ['primary-text', palette.colors.primary.text],
  ['cta', palette.colors.cta.DEFAULT],
  ['cta-hover', palette.colors.cta.hover],
  ['background-primary', palette.colors.background.primary],
  ['surface-secondary', palette.colors.background.surface],
  ['background-secondary', palette.colors.background.secondary],
  ['text-primary', palette.colors.text.primary],
  ['text-secondary', palette.colors.text.secondary],
  ['text-tertiary', palette.colors.text.tertiary],
  ['border-tertiary', palette.colors.border.tertiary],
  ['macro-carb', palette.colors.macro.carb],
  ['macro-fat', palette.colors.macro.fat],
  ['amber-400', palette.colors.amber['400']],
  ['steel-blue-400', palette.colors.steelBlue['400']],
  ['steel-blue-600', palette.colors.steelBlue['600']],
  ['danger-text', palette.colors.danger.text],
];

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [
    parseInt(h.slice(0, 2), 16),
    parseInt(h.slice(2, 4), 16),
    parseInt(h.slice(4, 6), 16),
  ];
}

// CSV (Excel / generic import)
const csvLines = ['name,hex,r,g,b'];
for (const [name, hex] of flat) {
  const [r, g, b] = hexToRgb(hex);
  csvLines.push(`${name},${hex},${r},${g},${b}`);
}
writeFileSync(join(outDir, 'palette.csv'), `${csvLines.join('\n')}\n`);

// CSS custom properties (Figma plugin / dev handoff)
const cssLines = ['/** Nutri-Pilot presentation palette — auto-generated */', ':root {'];
for (const [name, hex] of flat) {
  cssLines.push(`  --ppt-${name}: ${hex};`);
}
cssLines.push('}');
writeFileSync(join(outDir, 'palette.css'), `${cssLines.join('\n')}\n`);

// Figma Variables collection (import via Tokens Studio or manual)
const figmaTokens = {
  $metadata: { tokenSetOrder: ['Nutri-Pilot'] },
  'Nutri-Pilot': Object.fromEntries(
    flat.map(([name, hex]) => [
      name.replace(/-/g, '/'),
      { $type: 'color', $value: hex },
    ]),
  ),
};
writeFileSync(
  join(outDir, 'figma-tokens.json'),
  `${JSON.stringify(figmaTokens, null, 2)}\n`,
);

// PowerPoint theme color mapping (Office 2016+ custom theme XML fragment)
const ppt = palette.colors;
const accent1 = ppt.primary.DEFAULT.replace('#', '');
const accent2 = ppt.macro.carb.replace('#', '');
const accent3 = ppt.macro.fat.replace('#', '');
const accent4 = ppt.amber['400'].replace('#', '');
const accent5 = ppt.steelBlue['400'].replace('#', '');
const accent6 = ppt.danger.text.replace('#', '');
const dk1 = ppt.cta.DEFAULT.replace('#', '');
const lt1 = ppt.background.primary.replace('#', '');
const dk2 = ppt.text.secondary.replace('#', '');
const lt2 = ppt.background.surface.replace('#', '');

const themeXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!--
  Nutri-Pilot custom color scheme for PowerPoint.
  Import: Design → Variants → Colors → Customize Colors,
  or merge into theme1.xml inside a .thmx / .pptx zip.
  Generated by scripts/ppt-export-palette.mjs
-->
<a:clrScheme name="Nutri-Pilot" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">
  <a:dk1><a:srgbClr val="${dk1}"/></a:dk1>
  <a:lt1><a:srgbClr val="${lt1}"/></a:lt1>
  <a:dk2><a:srgbClr val="${dk2}"/></a:dk2>
  <a:lt2><a:srgbClr val="${lt2}"/></a:lt2>
  <a:accent1><a:srgbClr val="${accent1}"/></a:accent1>
  <a:accent2><a:srgbClr val="${accent2}"/></a:accent2>
  <a:accent3><a:srgbClr val="${accent3}"/></a:accent3>
  <a:accent4><a:srgbClr val="${accent4}"/></a:accent4>
  <a:accent5><a:srgbClr val="${accent5}"/></a:accent5>
  <a:accent6><a:srgbClr val="${accent6}"/></a:accent6>
  <a:hlink><a:srgbClr val="${accent1}"/></a:hlink>
  <a:folHlink><a:srgbClr val="${accent5}"/></a:folHlink>
</a:clrScheme>
`;
writeFileSync(join(outDir, 'powerpoint-clrScheme.xml'), themeXml);

// Keynote / Apple — plist-style reference
const keynote = flat.map(([name, hex]) => ({ name, hex, rgb: hexToRgb(hex) }));
writeFileSync(
  join(outDir, 'keynote-colors.json'),
  `${JSON.stringify({ name: 'Nutri-Pilot', colors: keynote }, null, 2)}\n`,
);

console.log(`Wrote ${flat.length} colors to ppt/export/`);
